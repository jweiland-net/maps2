namespace JWeiland\Maps2\Form\PoiPosition;

use TYPO3\CMS\Core\Page\AssetCollector;

/**
 * Loads the frontend assets of maps2 for the form element "Maps2PoiPosition".
 *
 * The asset identifiers are the same as in Partials/LoadAssets.html, so the
 * assets are loaded only once, if a maps2 plugin is on the same page.
 */
readonly class PoiPositionAssets
{
    private const GOOGLE_MAPS_API_URI = 'https://maps.googleapis.com/maps/api/js?';

    private const GOOGLE_MAPS_JAVASCRIPT = 'EXT:maps2/Resources/Public/JavaScript/GoogleMaps2.min.js';

    private const LEAFLET_STYLE_SHEET = 'EXT:maps2/Resources/Public/Css/Leaflet/Leaflet.css';

    private const LEAFLET_JAVASCRIPT = 'EXT:maps2/Resources/Public/JavaScript/leaflet.min.js';

    private const OPEN_STREET_MAP_JAVASCRIPT = 'EXT:maps2/Resources/Public/JavaScript/OpenStreetMap2.min.js';

    private const OPTIONS = ['useNonce' => true];

    public function __construct(
        private AssetCollector $assetCollector,
    ) {}

    public function load(string $mapProvider, string $googleMapsJavaScriptApiKey): void
    {
        if ($mapProvider === PoiPositionMapConfigurator::MAP_PROVIDER_OPEN_STREET_MAP) {
            $this->loadOpenStreetMap();
            return;
        }

        $this->loadGoogleMaps($googleMapsJavaScriptApiKey);
    }

    private function loadGoogleMaps(string $apiKey): void
    {
        // The nonce is added to the style tags, which are generated by Google Maps
        $this->assetCollector->addInlineStyleSheet('maps2-google-maps', ';', [], self::OPTIONS + ['priority' => true]);

        // "initMap" of GoogleMaps2.min.js is the callback of the Google Maps API
        $this->assetCollector->addJavaScript(
            'maps2-google-maps-api',
            self::GOOGLE_MAPS_API_URI
            . http_build_query(['key' => $apiKey, 'libraries' => 'places', 'callback' => 'initMap']),
            ['async' => 'async'],
            self::OPTIONS,
        );
        $this->assetCollector->addJavaScript(
            'maps2-google-maps',
            self::GOOGLE_MAPS_JAVASCRIPT,
            ['async' => 'async'],
            self::OPTIONS,
        );
    }

    private function loadOpenStreetMap(): void
    {
        // Leaflet has to be loaded synchronously. Else "L" is not defined.
        $this->assetCollector->addStyleSheet('maps2-osm', self::LEAFLET_STYLE_SHEET, [], self::OPTIONS);
        $this->assetCollector->addJavaScript('maps2-osm-leaflet', self::LEAFLET_JAVASCRIPT, [], self::OPTIONS);
        $this->assetCollector->addJavaScript('maps2-osm', self::OPEN_STREET_MAP_JAVASCRIPT, [], self::OPTIONS);
    }
}
